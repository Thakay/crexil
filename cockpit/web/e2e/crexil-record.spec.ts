import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {artifact} from './paths';

const source=readFileSync(fileURLToPath(new URL('../../../bench/sources/rc-keep/source.png',import.meta.url))).toString('base64');
const command=()=>({request_id:crypto.randomUUID(),actor:{kind:'human',name:'Record verification'}});

test('finds attributed decisions, revises once after a lost response, and returns through source history',async({page,request})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  const project=await(await request.post('/api/crexil/projects',{data:{...command(),name:`Decision study ${Date.now()}`,brief:'Choose a silhouette and revise its surface.'}})).json();
  const add=async(filename:string,parents:string[]=[])=>{
    const response=await request.post(`/api/crexil/projects/${project.id}/material`,{data:{...command(),filename,data_base64:source,parents,tool:parents.length?'Krita':'',explanation:parents.length?'Reported surface revision':''}});
    expect(response.ok()).toBe(true);return response.json();
  };
  const first=await add('Silhouette.png');
  const returned=await add('Krita edit.png',[first.node.id]);
  const selected=await request.put(`/api/crexil/directions/${first.direction.id}/selection`,{data:{...command(),actor:{kind:'agent',name:'Scout'},revision:first.direction.revision,node_ids:[first.node.id],reason:'Strong silhouette; uncertain surface.'}});
  expect(selected.ok()).toBe(true);
  for(let i=0;i<40;i++)expect((await request.post(`/api/crexil/projects/${project.id}/directions`,{data:{...command(),title:`Study ${i}`,setup:{prompt:`Material investigation ${i}`}}})).ok()).toBe(true);
  await page.goto(`/#/projects/${project.id}`);
  await page.getByRole('button',{name:'Record ›',exact:true}).click();
  const room=page.getByRole('region',{name:'Project record',exact:true});
  await room.getByRole('searchbox',{name:'Find in this project'}).fill('silhouette');
  await expect(room.getByRole('article',{name:'Display choice by Scout'})).toContainText('Strong silhouette');
  await room.getByRole('button',{name:'Revise reason',exact:true}).click();
  await room.getByRole('textbox',{name:'Your reason',exact:true}).fill('Keep the silhouette; revise the rough surface.');
  await room.getByRole('button',{name:'Material',exact:true}).click();
  await room.getByRole('button',{name:'Decisions',exact:true}).click();
  await expect(room.getByRole('textbox',{name:'Your reason',exact:true})).toHaveValue('Keep the silhouette; revise the rough surface.');
  let lost=true;
  await page.route(`**/api/crexil/projects/${project.id}/assessments`,async route=>{
    if(lost){lost=false;const response=await route.fetch();expect(response.status()).toBe(201);await route.abort('failed');}
    else await route.continue();
  });
  await room.getByRole('button',{name:'Save reason',exact:true}).click();
  await expect(room.getByRole('button',{name:'Confirm same save',exact:true})).toBeEnabled();
  await expect(room.getByRole('textbox',{name:'Your reason',exact:true})).toBeDisabled();
  await page.reload();await page.getByRole('button',{name:'Record ›',exact:true}).click();
  await expect(room.getByRole('textbox',{name:'Your reason',exact:true})).toHaveValue('Keep the silhouette; revise the rough surface.');
  await room.getByRole('button',{name:'Confirm same save',exact:true}).click();
  await expect(room.getByRole('textbox',{name:'Your reason',exact:true})).not.toBeVisible();
  const record=await(await request.get(`/api/crexil/projects/${project.id}/record`)).json();
  expect(record.decisions).toHaveLength(2);
  expect(record.decisions.map((item:{actor:{name:string}})=>item.actor.name)).toEqual(['Artist','Scout']);
  for(const width of [1440,1920]){
    await page.setViewportSize({width,height:900});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
    await page.screenshot({path:artifact(`record-decisions-${width}.png`)});
  }
  await room.getByRole('button',{name:'Material',exact:true}).click();
  await room.getByRole('searchbox',{name:'Find in this project'}).fill('Silhouette');
  const original=room.getByRole('button',{name:/Silhouette.png.*Inspect/});
  await original.click();
  const inspect=page.getByRole('region',{name:'Inspect material',exact:true});
  await expect(inspect.getByRole('heading',{name:'Source information'})).toBeVisible();
  await inspect.getByRole('button',{name:'Krita edit.png ›',exact:true}).click();
  await expect(inspect).toContainText('Returned external work. Relationships were reported by a participant.');
  await inspect.getByRole('button',{name:'Silhouette.png ›',exact:true}).first().click();
  await expect(inspect).toContainText('Display choice');
  await inspect.getByRole('button',{name:'Decisions and assessments ›',exact:true}).click();
  await expect(room.getByRole('article',{name:'Display choice by Scout'})).toBeVisible();
  await room.getByRole('button',{name:'Directions',exact:true}).click();
  const nestedDirection=room.getByRole('button',{name:'Open direction ›',exact:true});
  await nestedDirection.click();
  await expect(room).not.toBeVisible();
  await page.getByRole('button',{name:'Esc · Record',exact:true}).click();
  await expect(nestedDirection).toBeFocused();
  await room.getByRole('button',{name:'Esc · Inspect',exact:true}).click();
  await expect(inspect).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(inspect).not.toBeVisible();
  await expect(room.getByRole('searchbox')).toHaveValue('Silhouette');
  await expect(original).toBeFocused();
  await room.getByRole('button',{name:'Directions',exact:true}).click();
  await room.getByRole('searchbox').fill('Material investigation 39');
  await room.getByRole('button',{name:'Open direction ›',exact:true}).click();
  const drawer=page.getByRole('region',{name:'Preparation',exact:true});
  await expect(drawer.getByRole('textbox',{name:'Prompt',exact:true})).toHaveValue('Material investigation 39');
  await drawer.getByRole('button',{name:'Close · Esc',exact:true}).click();
  await expect(room.getByRole('searchbox')).toHaveValue('Material investigation 39');
  await expect(room.getByRole('button',{name:'Open direction ›',exact:true})).toBeFocused();
  await room.getByRole('button',{name:'Esc · Project',exact:true}).click();
  await expect(room).not.toBeVisible();
  const snapshot=await(await request.get(`/api/crexil/projects/${project.id}`)).json();
  expect(snapshot.turns).toEqual([]);
  expect(snapshot.nodes.find((node:{id:string})=>node.id===returned.node.id).parents).toEqual([first.node.id]);
  expect(snapshot.directions.find((direction:{id:string})=>direction.id===first.direction.id).selection).toEqual([first.node.id]);
  expect(errors).toEqual([]);
});

test('assessment from inspection preserves authorship and returns to the inspected material',async({page,request})=>{
  const project=await(await request.post('/api/crexil/projects',{data:{...command(),name:`Assessment study ${Date.now()}`}})).json();
  const imported=await(await request.post(`/api/crexil/projects/${project.id}/material`,{data:{...command(),filename:'Reference.png',data_base64:source}})).json();
  await page.goto(`/#/projects/${project.id}?material=${imported.node.id}`);
  const inspect=page.getByRole('region',{name:'Inspect material',exact:true});
  await inspect.getByRole('button',{name:'Decisions and assessments ›',exact:true}).click();
  const room=page.getByRole('region',{name:'Project record',exact:true});
  await room.getByRole('button',{name:'Add assessment',exact:true}).click();
  await room.getByRole('textbox',{name:'Your reason',exact:true}).fill('Useful structure, but the material needs another direction.');
  await room.getByRole('button',{name:'Save reason',exact:true}).click();
  await expect(room.getByRole('article',{name:'Assessment by Artist'})).toContainText('Useful structure');
  await room.getByRole('button',{name:'Esc · Inspect',exact:true}).click();
  await expect(inspect).toBeVisible();
  await expect(inspect.getByRole('article',{name:'Assessment by Artist'})).toContainText('Useful structure');
  await page.reload();await expect(inspect.getByRole('article',{name:'Assessment by Artist'})).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:/Useful structure, but the material needs another direction.*Artist/}).click();
  await expect(room.getByRole('article',{name:'Assessment by Artist'})).toContainText('Useful structure');
  await page.getByRole('button',{name:'Tray ›',exact:true}).click();
  await expect(room).not.toBeVisible();
  await expect(page.getByRole('heading',{name:'Your directions are on the project.',exact:true})).toBeVisible();
  const data=await(await request.get(`/api/crexil/projects/${project.id}`)).json();
  expect(data.directions[0].selection).toEqual([]);
  expect(data.turns).toEqual([]);
});

test('uncertain revision keeps its subjects after a competing decision and reload',async({page,request})=>{
  const project=await(await request.post('/api/crexil/projects',{data:{...command(),name:`Competing opinions ${Date.now()}`}})).json();
  const imported=await(await request.post(`/api/crexil/projects/${project.id}/material`,{data:{...command(),filename:'Study.png',data_base64:source}})).json();
  const path=`/api/crexil/projects/${project.id}/assessments`;
  const original=await(await request.post(path,{data:{...command(),node_ids:[imported.node.id],reason:'First assessment'}})).json();
  await page.goto(`/#/projects/${project.id}`);await page.getByRole('button',{name:'Record ›',exact:true}).click();
  const room=page.getByRole('region',{name:'Project record',exact:true});
  await room.getByRole('button',{name:'Revise reason',exact:true}).click();
  await room.getByRole('textbox',{name:'Your reason',exact:true}).fill('My separate assessment');
  let lost=true;await page.route(`**${path}`,async route=>{if(lost){lost=false;await route.abort('failed');}else await route.continue();});
  await room.getByRole('button',{name:'Save reason',exact:true}).click();
  await expect(room.getByRole('button',{name:'Confirm same save',exact:true})).toBeEnabled();
  expect((await request.post(path,{data:{...command(),actor:{kind:'agent',name:'Scout'},previous_id:original.event_id,reason:'A competing decision'}})).ok()).toBe(true);
  await page.reload();await page.getByRole('button',{name:'Record ›',exact:true}).click();
  await room.getByRole('button',{name:'Confirm same save',exact:true}).click();
  await expect(room.getByRole('alert')).toContainText('newer revision');
  await room.getByRole('button',{name:'Keep as a separate assessment',exact:true}).click();
  await room.getByRole('button',{name:'Save reason',exact:true}).click();
  await expect(room.getByRole('article',{name:'Assessment by Artist'})).toContainText('My separate assessment');
  const record=await(await request.get(`/api/crexil/projects/${project.id}/record`)).json();
  expect(record.decisions).toHaveLength(3);expect(record.decisions[0].node_ids).toEqual([imported.node.id]);
  expect(record.decisions[0].previous_id).toBeNull();
  await request.post(path,{data:{...command(),actor:{kind:'agent',name:'Reviewer'},node_ids:[imported.node.id],reason:'New live assessment'}});
  await expect(room.getByRole('article',{name:'Assessment by Reviewer'})).toContainText('New live assessment');
  await room.getByRole('article',{name:'Assessment by Reviewer'}).getByRole('button',{name:'Study.png ›',exact:true}).click();
  const inspect=page.getByRole('region',{name:'Inspect material',exact:true});
  await request.post(path,{data:{...command(),actor:{kind:'agent',name:'Second reviewer'},node_ids:[imported.node.id],reason:'Live while inspecting'}});
  await expect(inspect.getByRole('article',{name:'Assessment by Second reviewer'})).toContainText('Live while inspecting');
});
